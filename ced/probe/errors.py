"""探针层的错误类型。

**关键语义**：链路探测失败必须抛错，绝不允许合成一个"看起来像观测"的结果。
合成出来的观测必然与基线不同，会把"探测失败"整片变成假阳性安全结论。

这里区分两种"没拿到观测"，因为它们的处置完全不同：
  * ``ProbeUnreachable`` —— 链路故障（端口没人听、探针没起来）→ **中止**；
  * ``ProbeRejected``    —— 前置收到了字节但按自身策略拒绝转发（真实 nginx 对畸形请求
                            返回 400 就属此类）→ **跳过这一条并计数**，不中止、不合成。
"""
from __future__ import annotations


class ProbeUnreachable(RuntimeError):
    """探针不可达、或链路根本没起来。链路故障，必须中止。"""


class ProbeRejected(RuntimeError):
    """前置收到字节但没有向后端转发任何字节（按自身策略拒绝）。

    这是**前置行为的如实记录**，不是链路故障。真实前置（nginx / Envoy）会对畸形请求
    直接返回 4xx 而不转发，属正常行为；若把它当故障，一轮扫描会在第一条畸形请求上崩掉。
    处置：跳过该条用例并计数 —— 既不合成一个后端视角，也不谎称探过。
    """
